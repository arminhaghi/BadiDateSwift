// Generates the Swift data files from a checkout of https://github.com/janrg/badiDate
//
//   node generate-swift-data.mjs /path/to/badiDate
//
// Writes into ../Sources/BadiDateSwift/Generated/. Re-run after an upstream data change.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const upstream = process.argv[2];
if (!upstream) {
    console.error('usage: node generate-swift-data.mjs /path/to/badiDate');
    process.exit(1);
}
const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, '..', 'Sources', 'BadiDateSwift', 'Generated');
fs.mkdirSync(outDir, { recursive: true });

const header = (source) =>
    `// Generated by Scripts/generate-swift-data.mjs from badiDate's ${source}. Do not edit by hand.\n` +
    `// badiDate is Copyright (c) 2016 Jan Greis, MIT licensed.\n\n`;

// The upstream data files are plain object literals with an ES export at the end.
const load = (file) => {
    const source = fs
        .readFileSync(path.join(upstream, file), 'utf8')
        .replace(/export\s*\{/, 'return {')
        .replace(/const (use)?[cC]lockLocations? = \([\s\S]*$/, 'return { clockLocations };');
    return new Function(source)();
};

const swiftString = (value) =>
    JSON.stringify(value.replaceAll('&#8207;', '‏')).replaceAll('‏', '\\u{200F}');

// Year table
{
    const source = fs.readFileSync(path.join(upstream, 'src/badiYears.ts'), 'utf8');
    const entries = source.match(/'[a-z0-9]{4}'/g).map((entry) => entry.slice(1, -1));
    let out = header('src/badiYears.ts');
    out += 'enum BadiYearTable {\n';
    out += '    /// First Badí‘ year covered by the table. Earlier years follow the fixed pre-172 B.E. rules.\n';
    out += '    static let firstYear = 172\n\n';
    out += `    static let count = ${entries.length}\n\n`;
    out += '    /// Four base-36 digits per year: day in March of Naw-Rúz, length of Ayyám-i-Há, then month and day of\n';
    out += '    /// the Birth of the Báb.\n';
    out += '    static let packed =\n';
    const lines = [];
    for (let i = 0; i < entries.length; i += 24) {
        lines.push(`        "${entries.slice(i, i + 24).join('')}"`);
    }
    out += `${lines.join(' +\n')}\n}\n`;
    fs.writeFileSync(path.join(outDir, 'BadiYearTable.swift'), out);
}

// Clock location polygons
{
    const { clockLocations } = load('src/clockLocations.ts');
    let out = header('src/clockLocations.ts');
    out += 'enum ClockLocationPolygons {\n';
    out += '    // Each polygon is a flat list of longitude, latitude pairs.\n';
    for (const [name, polygons] of Object.entries(clockLocations)) {
        out += `    static let ${name.toLowerCase()}: [[Double]] = [\n`;
        for (const polygon of polygons) {
            out += `        [${polygon.map(([x, y]) => `${x}, ${y}`).join(', ')}],\n`;
        }
        out += '    ]\n';
    }
    out += '}\n';
    fs.writeFileSync(path.join(outDir, 'ClockLocationPolygons.swift'), out);
}

// Locales
{
    const codes = ['en', 'en-us', 'ar', 'de', 'es', 'fa', 'fr', 'lv', 'nl', 'pt', 'ru', 'sv', 'zh'];
    const tables = ['month', 'monthL', 'holyDay', 'weekday', 'weekdayAbbr3', 'weekdayAbbr2', 'weekdayL', 'yearInVahid'];
    const strings = ['vahid', 'kulliShay', 'BE', 'badiCalendar', 'unicodeCharForZero', 'defaultFormat'];
    const identifier = (code) => code.replace(/-(.)/, (_, c) => c.toUpperCase());
    let out = header('src/locale/*.ts');
    out += 'extension BadiLocaleData {\n';
    out += `    static let all: [String: BadiLocaleData] = [\n`;
    out += codes.map((code) => `        ${JSON.stringify(code)}: ${identifier(code)},`).join('\n');
    out += '\n    ]\n';
    for (const code of codes) {
        const locale = load(`src/locale/${code}.ts`);
        out += `\n    static let ${identifier(code)} = BadiLocaleData(\n`;
        const args = [];
        for (const table of tables) {
            if (locale[table] === undefined) continue;
            const items = Object.entries(locale[table]).map(([index, value]) => `${index}: ${swiftString(value)}`);
            args.push(`        ${table}: [\n            ${items.join(',\n            ')},\n        ]`);
        }
        for (const key of strings) {
            if (locale[key] === undefined) continue;
            const label = key === 'BE' ? 'be' : key;
            args.push(`        ${label}: ${swiftString(locale[key])}`);
        }
        out += `${args.join(',\n')}\n    )\n`;
    }
    out += '}\n';
    fs.writeFileSync(path.join(outDir, 'BadiLocaleData+Generated.swift'), out);
}

console.log(`Wrote Swift data files to ${outDir}`);
